"""Bundle the web app into one self-contained HTML file.

Browsers refuse to load ES modules from file:// pages, so web/index.html only
works when served over http. This writes web/kiln-controller.html: the same
page with the stylesheet and all modules inlined as one classic script, so it
can be opened straight from disk (or copied anywhere on its own).

    python scripts/build_web.py
"""

import pathlib
import re

WEB = pathlib.Path(__file__).resolve().parent.parent / "web"
OUT = WEB / "kiln-controller.html"

# Dependency order: each module only imports from modules above it.
MODULES = ["chart.js", "device.js", "tuning.js", "program.js", "demo.js", "app.js"]

IMPORT_RE = re.compile(r'^import\s*\{([^}]*)\}\s*from\s*"\./([\w.]+)";\s*$', re.M)
EXPORT_DECL_RE = re.compile(r"^export\s+(?=(?:async\s+)?function\b|class\b|const\b|let\b)", re.M)
EXPORT_NAME_RE = re.compile(r"^export\s+(?:async\s+)?(?:function\*?|class|const|let)\s+([A-Za-z_$][\w$]*)", re.M)


def bundle_module(name, src):
    if re.search(r"^\s*export\s*(\{|default\b|\*)", src, re.M) or "import.meta" in src:
        raise SystemExit(f"{name}: unsupported import/export form; extend build_web.py")
    exports = EXPORT_NAME_RE.findall(src)

    def imp(m):
        if m.group(2) not in MODULES[:MODULES.index(name)]:
            raise SystemExit(f"{name}: imports {m.group(2)} before it is bundled")
        return f"const {{{m.group(1)}}} = __modules[{m.group(2)!r}];"

    body = IMPORT_RE.sub(imp, src)
    if re.search(r"^\s*import\b", body, re.M):
        raise SystemExit(f"{name}: unsupported import form; extend build_web.py")
    body = EXPORT_DECL_RE.sub("", body)
    ret = ", ".join(exports)
    return f"// ---- {name} ----\n__modules[{name!r}] = (() => {{\n{body}\nreturn {{ {ret} }};\n}})();\n"


def main():
    html = (WEB / "index.html").read_text(encoding="utf-8")
    css = (WEB / "style.css").read_text(encoding="utf-8")
    js = '"use strict";\nconst __modules = {};\n' + "".join(
        bundle_module(m, (WEB / m).read_text(encoding="utf-8")) for m in MODULES)
    if "</script" in js or "</style" in css:
        raise SystemExit("source contains a closing tag that would end the inline block")

    def swap(old, new):
        nonlocal html
        if html.count(old) != 1:
            raise SystemExit(f"index.html: expected exactly one {old!r}")
        html = html.replace(old, new)

    swap('<link rel="stylesheet" href="style.css">', f"<style>\n{css}</style>")
    # Classic inline scripts can't be deferred, so run it at the end of <body>
    # like the deferred module did. Drop the file:// redirect meant for index.html.
    swap('<script type="module" src="app.js"></script>', "")
    html = re.sub(r"\s*<script data-file-redirect>.*?</script>", "", html, flags=re.S)
    swap("</body>", f"<script>\n{js}</script>\n</body>")
    # The banner goes after the doctype; anything before it triggers quirks mode.
    swap("<!doctype html>\n", "<!doctype html>\n<!-- Generated by scripts/build_web.py from web/*.js and style.css. Edit those, not this file. -->\n")
    OUT.write_text(html, encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({OUT.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main()
